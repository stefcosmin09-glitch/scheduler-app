"""The migration history must be able to build a database from nothing.

Fifteen migrations once stood here, and `flask db upgrade` against an empty
database failed on the first foreign key, because the first of them created an
`invoice` table pointing at a `job` table that nothing in the chain ever
created. They had been autogenerated against a database that already had those
tables, so they only ever ran on top of an existing schema.

They are now one initial migration generated from the models. These tests hold
that in place:

  a fresh database builds
  the schema it builds matches what the models declare
  it survives a downgrade and comes back
  the entrypoint used at deploy time moves an existing database onto the new
  head without losing rows

The drift test is the one that earned its keep. Autogenerating against an empty
database only sees the model metadata, so the two indexes that had been created
by migrations and never declared in models.py would have vanished, taking
TimeEntry.running_for() from indexed to a full table scan with it.
"""
import os
import sqlite3
import subprocess
import sys

import pytest
from sqlalchemy import create_engine, inspect, text

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VERSIONS = os.path.join(ROOT, 'migrations', 'versions')
INITIAL = '0001_initial_schema'
# The app refuses to start without one, and the deploy provides it, so every
# subprocess here needs it too.
TEST_ENV = {'SECRET_KEY': 'test-key-not-used-outside-this-scratch-directory'}


def _db_url(path):
    return 'sqlite:///' + path.replace('\\', '/')


def _env(db_path):
    return dict(os.environ, DATABASE_URL=_db_url(db_path), **TEST_ENV)


def _flask_db(db_path, *args):
    result = subprocess.run([sys.executable, '-m', 'flask', 'db'] + list(args),
                            cwd=ROOT, env=_env(db_path),
                            capture_output=True, text=True)
    return result


@pytest.fixture
def built(tmp_path):
    """An empty database with the migrations applied."""
    path = str(tmp_path / 'built.db')
    result = _flask_db(path, 'upgrade')
    assert result.returncode == 0, result.stdout[-2000:] + result.stderr[-2000:]
    return path


def _tables(path):
    conn = sqlite3.connect(path)
    try:
        return {r[0] for r in conn.execute(
            "select name from sqlite_master where type='table' "
            "and name not like 'sqlite_%'")}
    finally:
        conn.close()


def _indexes(path):
    found = {}
    conn = sqlite3.connect(path)
    try:
        for table in _tables(path) - {'alembic_version'}:
            for row in conn.execute('PRAGMA index_list("%s")' % table):
                if row[1].startswith('sqlite_autoindex_'):
                    continue
                cols = tuple(c[2] for c in
                             conn.execute('PRAGMA index_info("%s")' % row[1]))
                found[(table, row[1])] = (cols, bool(row[2]))
        return found
    finally:
        conn.close()


# --- the history itself ----------------------------------------------------

def test_single_initial_revision():
    files = [f for f in os.listdir(VERSIONS) if f.endswith('.py')]
    assert len(files) == 1, 'expected one migration, found %s' % files


def test_initial_is_the_only_head():
    """More than one head would make `stamp head` ambiguous."""
    result = _flask_db(os.path.join(ROOT, 'instance', 'scheduler.db'), 'heads')
    assert '0001_initial_schema' in result.stdout, result.stdout
    assert result.stdout.count('(head)') <= 1, result.stdout


def test_initial_has_no_parent():
    with open(os.path.join(VERSIONS, '0001_initial_schema.py'),
              encoding='utf-8') as handle:
        source = handle.read()
    assert 'down_revision = None' in source, 'the initial revision has no parent'


# --- building from nothing -------------------------------------------------

def test_empty_database_upgrades(built):
    assert 'user' in _tables(built)
    for table in ('user', 'job', 'invoice', 'payment', 'business_profile',
                  'time_entry', 'expense', 'ai_usage'):
        assert table in _tables(built), '%s missing' % table


def test_stamped_at_head(built):
    conn = sqlite3.connect(built)
    try:
        assert conn.execute(
            'select version_num from alembic_version').fetchone()[0] == INITIAL
    finally:
        conn.close()


def test_server_defaults_survive_the_build(built):
    """A column added without a server_default leaves existing rows NULL, which
    is how duration_minutes went wrong the first time.
    """
    conn = sqlite3.connect(built)
    try:
        for table, column, expected in (('user', 'currency', "'GBP'"),
                                        ('business_profile', 'tax_country', "'UK'"),
                                        ('job', 'duration_minutes', "'60'")):
            default = [row[4] for row in conn.execute(
                'PRAGMA table_info("%s")' % table) if row[1] == column][0]
            assert default == expected, '%s.%s default is %r' % (
                table, column, default)
    finally:
        conn.close()


def test_cascade_is_declared(built):
    assert "ondelete='CASCADE'" in open(
        os.path.join(VERSIONS, '0001_initial_schema.py'),
        encoding='utf-8').read(), 'ON DELETE CASCADE on time_entry.job_id'


def test_indexes_are_created(built):
    indexes = _indexes(built)
    assert ('time_entry', 'ix_time_entry_user_open') in indexes, \
        'the open-timer lookup lost its index'
    assert ('user', 'ix_user_calendar_token') in indexes, \
        'the calendar token index is missing'
    assert indexes[('time_entry', 'ix_time_entry_user_open')][0] == \
        ('user_id', 'ended_at'), 'wrong columns'
    assert indexes[('user', 'ix_user_calendar_token')][1] is True, \
        'the calendar token index must be unique'


def test_database_rejects_a_duplicate_token(built):
    conn = sqlite3.connect(built)
    try:
        conn.execute("insert into user (username,email,password,currency,"
                     "calendar_token) values ('a','a@t','x','GBP','dup')")
        conn.execute("insert into user (username,email,password,currency,"
                     "calendar_token) values ('b','b@t','x','GBP','dup')")
        conn.commit()
        rejected = False
    except sqlite3.IntegrityError:
        conn.rollback()
        rejected = True
    finally:
        conn.close()
    assert rejected, 'two users can share a calendar token'


def test_null_tokens_are_allowed(built):
    """A unique index rejects duplicate values, not duplicate NULLs, so every
    user who never asked for a calendar has to be insertable.
    """
    conn = sqlite3.connect(built)
    try:
        for name in ('c', 'd'):
            conn.execute("insert into user (username,email,password,currency) "
                         "values (?,?, 'x','GBP')", (name, '%s@t' % name))
        conn.commit()
        assert conn.execute('select count(*) from user').fetchone()[0] == 2
    finally:
        conn.close()


def test_downgrade_then_upgrade(built):
    down = _flask_db(built, 'downgrade', 'base')
    assert down.returncode == 0, down.stdout[-2000:] + down.stderr[-2000:]
    assert _tables(built) == {'alembic_version'}, 'nothing should be left'

    up = _flask_db(built, 'upgrade')
    assert up.returncode == 0, up.stdout[-2000:] + up.stderr[-2000:]
    assert 'user' in _tables(built), 'the schema came back'


# --- the schema matches the models ----------------------------------------

def _model_indexes(metadata):
    """Named indexes and unique constraints as the models declare them."""
    named, unnamed = {}, {}
    for table in metadata.sorted_tables:
        for index in table.indexes:
            named[(table.name, index.name)] = (
                tuple(c.name for c in index.columns), bool(index.unique))
        for constraint in table.constraints:
            if constraint.__class__.__name__ == 'UniqueConstraint':
                unnamed[(table.name,
                         tuple(sorted(c.name for c in constraint.columns)))] = True
    return named, unnamed


def _db_schema(path):
    """The same facts as SQLite reports them, with its autoindex names folded
    back into plain unique constraints so the two sides line up.
    """
    conn = sqlite3.connect(path)
    try:
        named, unnamed = {}, {}
        tables = _tables(path) - {'alembic_version'}
        for table in tables:
            for row in conn.execute('PRAGMA index_list("%s")' % table):
                cols = tuple(c[2] for c in
                             conn.execute('PRAGMA index_info("%s")' % row[1]))
                if row[1].startswith('sqlite_autoindex_'):
                    unnamed[(table, tuple(sorted(cols)))] = bool(row[2])
                else:
                    named[(table, row[1])] = (cols, bool(row[2]))
        return named, unnamed, tables
    finally:
        conn.close()


def test_no_drift_between_models_and_migrations(built):
    """The check that caught the two lost indexes, kept so it cannot recur.

    Compares a database built by the migrations against what the models
    declare. An index that exists in one and not the other shows up here rather
    than in production.

    The comparison is made against the metadata of the already-imported app
    rather than by building a second database in a subprocess, because
    reimporting the app module would leave a second SQLAlchemy instance behind
    and break every test that runs after this one.
    """
    from _support import db as database

    want_named, want_unnamed = _model_indexes(database.metadata)
    got_named, got_unnamed, tables = _db_schema(built)

    model_tables = {t.name for t in database.metadata.sorted_tables}
    drifted = []
    for table in sorted(model_tables - tables):
        drifted.append('table %s is in the models but not in the migrations'
                       % table)
    for table in sorted(tables - model_tables):
        drifted.append('table %s is in the migrations but not in the models'
                       % table)
    for key in sorted(set(want_named) - set(got_named)):
        drifted.append('%s.%s is in the models but not in the migrations' % key)
    for key in sorted(set(got_named) - set(want_named)):
        drifted.append('%s.%s is in the migrations but not in the models' % key)
    for key in sorted(set(want_named) & set(got_named)):
        if want_named[key] != got_named[key]:
            drifted.append('%s.%s differs: models %r, migrations %r'
                           % (key[0], key[1], want_named[key], got_named[key]))
    for key in sorted(set(want_unnamed) - set(got_unnamed)):
        drifted.append('unique %s%s is in the models but not in the migrations'
                       % key)
    for key in sorted(set(got_unnamed) - set(want_unnamed)):
        drifted.append('unique %s%s is in the migrations but not in the models'
                       % key)

    assert not drifted, 'schema drift:\n  ' + '\n  '.join(drifted)


