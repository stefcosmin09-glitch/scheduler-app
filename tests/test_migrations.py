def test_entrypoint_builds_an_empty_database(tmp_path):
    path = str(tmp_path / 'deploy-empty.db')
    env = _env(path)
    result = subprocess.run([sys.executable, 'migrate.py'], cwd=ROOT, env=env,
                            capture_output=True, text=True)
    assert result.returncode == 0, result.stdout[-2000:] + result.stderr[-2000:]
    assert 'aplic migrarile' in result.stdout, result.stdout
    assert 'user' in _tables(path), 'the schema was not created'


def test_entrypoint_is_idempotent(built):
    env = _env(built)
    result = subprocess.run([sys.executable, 'migrate.py'], cwd=ROOT, env=env,
                            capture_output=True, text=True)
    assert result.returncode == 0, result.stdout[-2000:] + result.stderr[-2000:]
    assert 'user' in _tables(built)


def test_entrypoint_stamps_a_squashed_revision(tmp_path):
    """A database created before the squash carries a revision id the script
    directory no longer has. Plain `flask db upgrade` fails on it, so the
    entrypoint has to re-stamp instead.
    """
    path = str(tmp_path / 'legacy.db')
    engine = create_engine(_db_url(path))
    with engine.begin() as conn:
        conn.execute(text('create table user (id integer primary key, '
                          'username varchar, email varchar)'))
        conn.execute(text('create table alembic_version '
                          '(version_num varchar(32) primary key)'))
        conn.execute(text("insert into alembic_version values "
                          "('e5f6a7b8c9d0')"))
    engine.dispose()

    plain = _flask_db(path, 'upgrade')
    assert plain.returncode != 0, \
        'expected plain upgrade to fail on an unknown revision'

    env = _env(path)
    result = subprocess.run([sys.executable, 'migrate.py'], cwd=ROOT, env=env,
                            capture_output=True, text=True)
    assert result.returncode == 0, result.stdout[-2000:] + result.stderr[-2000:]
    assert 'stamp' in result.stdout, result.stdout

    conn = sqlite3.connect(path)
    try:
        assert conn.execute('select version_num from alembic_version'
                            ).fetchone()[0] == INITIAL
        assert conn.execute('select count(*) from user').fetchone()[0] == 0, \
            'the existing tables were disturbed'
    finally:
        conn.close()
